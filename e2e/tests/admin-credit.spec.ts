import { expect, test } from '@playwright/test';
import { adminSidebar, isMobile, signInDiAsAdmin, tap } from './helpers';

// Real API, real staff MFA and isolated test customers. No routed/mocked financial success.
test('operator records evidenced receivables, partial repayment and immutable reversal with reload persistence', async ({ page }) => {
  await signInDiAsAdmin(page);
  if (isMobile(page)) await tap(page.getByRole('button', { name: 'باز کردن منو' }));
  await tap(adminSidebar(page).getByRole('link', { name: 'مشتریان', exact: true }));
  const suffix = Date.now().toString().slice(-9);
  await tap(page.getByRole('button', { name: 'مشتری جدید' }));
  const create = page.getByRole('dialog', { name: 'مشتری جدید' });
  await create.getByRole('textbox', { name: 'موبایل' }).fill(`09${suffix}`);
  await create.getByRole('textbox', { name: 'نام', exact: true }).fill('آزمون اعتبار');
  await tap(create.getByRole('button', { name: 'ذخیره' }));
  await expect(create).toBeHidden();
  await tap(page.getByRole('row').filter({ hasText: suffix }).getByRole('button', { name: 'جزئیات' }));
  await tap(page.getByRole('link', { name: 'اعتبار و دفترکل مشتری' }));
  await expect(page).toHaveURL(/\/customers\/[^/]+\/credit$/);
  await expect(page.getByText('برای این مشتری هنوز حساب اعتباری ثبت نشده است.')).toBeVisible();
  await tap(page.getByRole('button', { name: 'تنظیم اعتبار', exact: true }));
  const policy = page.getByRole('dialog', { name: 'تنظیم اعتبار مشتری' });
  await policy.getByRole('combobox', { name: 'وضعیت اعتبار' }).dispatchEvent('mousedown');
  await tap(page.getByRole('option', { name: 'فعال', exact: true }));
  await policy.getByRole('textbox', { name: 'سقف اعتبار (ریال)' }).fill('5000000');
  await policy.getByRole('textbox', { name: 'مهلت پرداخت (روز)' }).fill('30');
  await tap(policy.getByRole('button', { name: 'تأیید و ثبت' }));
  await expect(policy).toBeHidden();
  await tap(page.getByRole('button', { name: 'ثبت ماندهٔ اول دوره', exact: true }));
  const opening = page.getByRole('dialog', { name: 'ثبت ماندهٔ اول دوره' });
  await opening.getByRole('textbox', { name: 'مبلغ سند (ریال)' }).fill('1000000');
  await opening.getByRole('textbox', { name: 'شناسهٔ سند مرجع' }).fill(`isolated-opening-${suffix}`);
  const tomorrow = new Date(Date.now() + 86400000);
  const localTomorrow = new Date(tomorrow.getTime() - tomorrow.getTimezoneOffset() * 60000).toISOString().slice(0, 16);
  await opening.getByLabel('سررسید (زمان محلی)').fill(localTomorrow);
  await tap(opening.getByRole('button', { name: 'تأیید و ثبت' }));
  await expect(opening).toBeHidden();
  await expect(page.getByTestId('credit-outstanding')).toContainText('۱٬۰۰۰٬۰۰۰ ریال');
  await page.reload();
  await expect(page.getByTestId('credit-outstanding')).toContainText('۱٬۰۰۰٬۰۰۰ ریال');
  await expect(page.getByRole('table', { name: 'اسناد بدهی مشتری' })).toContainText('پرداخت‌نشده');
  await expect(page.getByRole('button', { name: 'ثبت ماندهٔ اول دوره', exact: true })).toHaveCount(0);

  await tap(page.getByRole('button', { name: 'ثبت دریافت واقعی', exact: true }));
  const receipt = page.getByRole('dialog', { name: 'ثبت دریافت واقعی' });
  await receipt.getByRole('textbox', { name: 'مبلغ دریافت (ریال)' }).fill('۵۰۰۰۰۰');
  await receipt.getByRole('textbox', { name: 'شناسهٔ سند مرجع' }).fill(`isolated-receipt-${suffix}`);
  await receipt.getByRole('textbox', { name: /تخصیص به/ }).fill('۵۰۰۰۰۰');
  await tap(receipt.getByRole('button', { name: 'تأیید و ثبت' }));
  await expect(receipt).toBeHidden();
  await expect(page.getByTestId('credit-outstanding')).toContainText('۵۰۰٬۰۰۰ ریال');
  await expect(page.getByRole('table', { name: 'اسناد بدهی مشتری' })).toContainText('پرداخت جزئی');
  await page.reload();
  await expect(page.getByTestId('credit-outstanding')).toContainText('۵۰۰٬۰۰۰ ریال');
  const ledger = page.getByRole('table', { name: 'گردش دفترکل اعتبار' });
  await tap(ledger.getByRole('row').filter({ hasText: 'دریافت وجه' }).getByRole('button', { name: 'برگشت دریافت' }));
  const reversal = page.getByRole('dialog', { name: 'برگشت دریافت' });
  await reversal.getByRole('textbox', { name: 'شناسهٔ سند مرجع' }).fill(`isolated-reversal-${suffix}`);
  await reversal.getByRole('textbox', { name: 'دلیل اصلاح' }).fill('اصلاح دریافت در آزمون ایزوله');
  await tap(reversal.getByRole('button', { name: 'تأیید و ثبت' }));
  await expect(reversal).toBeHidden();
  await page.reload();
  await expect(page.getByTestId('credit-outstanding')).toContainText('۱٬۰۰۰٬۰۰۰ ریال');
  await expect(ledger).toContainText('برگشت دریافت');
  await expect(ledger.getByRole('row').filter({ hasText: 'دریافت وجه' }).getByRole('button', { name: 'برگشت دریافت' })).toBeDisabled();
});
